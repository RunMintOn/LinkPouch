export function t(language: Language, key: TranslationKey, values: Values = {}): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function viewLabel(language: Language, view: QueueView): string {
  return t(language, `view.${view}` as TranslationKey);
}

export function captureOutcomeLabel(language: Language, outcome: CaptureOutcome): string {
  return t(language, `popup.${outcome}` as TranslationKey);
}
